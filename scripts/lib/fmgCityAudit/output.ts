export function jsonString(value: unknown): string {
  return (
    JSON.stringify(
      value,
      (_key, entry) => (ArrayBuffer.isView(entry) ? Array.from(entry as unknown as ArrayLike<number>) : entry),
      2
    ) + "\n"
  );
}
function csvCell(value: unknown): string {
  if (value === undefined || value === null) return "";
  let text = typeof value === "object" ? JSON.stringify(value) : String(value);
  // Preserve numeric negatives. Protect only string inputs, including leading whitespace/control characters.
  if (typeof value === "string" && /^[\s\u0000-\u001f]*[=+@-]/.test(text)) text = `'${text}`;
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}
export function csvString(rows: readonly RecordValue[], columns: readonly string[]): string {
  return [columns.join(","), ...rows.map(row => columns.map(key => csvCell(row[key])).join(","))].join("\r\n") + "\r\n";
}
export function summaryMarkdown(report: AuditReport): string {
  const flagged = report.findings.filter(f => f.status === "flagged");
  const origins = report.burgs.filter(b => b.isOrigin);
  return [
    "# FMG都市文脈監査",
    "",
    `起点都市: ${origins.length}、出力都市: ${report.burgs.length}、街道分岐: ${report.connections.length}、Directions結果: ${report.directions.length}。`,
    `検出: error=${flagged.filter(f => f.severity === "error").length}、warning=${flagged.filter(f => f.severity === "warning").length}、info=${flagged.filter(f => f.severity === "info").length}。skipped=${report.findings.filter(f => f.status === "skipped").length}。`,
    "",
    "都市間距離はDirectionsの共通計測処理を使用。街道の生pointsの距離は別列。主経路が当該街道と一致するとは限らない。",
    "",
    `距離単位: ${report.metadata.distanceUnit ?? "不明"}（${report.metadata.distanceUnitSource}）。heightExponent=${report.metadata.heightExponent}（${report.metadata.heightExponentSource}）。`,
    `移動手段: ${report.metadata.travelMode}、avoidSea=${report.metadata.avoidSea}、preferSea=${report.metadata.preferSea}。`,
    "",
    "## 起点都市",
    "",
    ...origins.map(
      b =>
        `- ${b.label}: 人口=${b.populationPersons ?? "不明"}、group=${b.groupRaw ?? "不明"}、城=${b.citadel}、市壁=${b.walls}、国家=${b.stateName ?? b.stateId}、河岸=${b.riverId ?? "不明"}/${b.riverBank ?? "不明"}`
    ),
    "",
    "## 主な検出",
    "",
    ...(flagged.length
      ? flagged.slice(0, 30).map(f => `- ${f.severity}: ${f.ruleId} / ${f.subject}: ${f.message}`)
      : ["整合性エラー・警告はありません。"]),
    "",
    "## 実装範囲",
    "",
    "保存値・生街道の接続先・Directions・基本整合性を出力。軍事量は兵種の保存単位を保持し、人員数へ未検証の換算を行わない。経済値の期間・単位も推測しない。",
    "",
    "完全なCE descriptorとの照合、登録陸路の施設復元、史料に基づく立地判定、城位置・建物密度の判定、橋の斜交監査はskipped。findingsの理由を参照。",
    ""
  ].join("\n");
}
